import { createHmac } from "node:crypto";
import { mkdir, readFile, rm, stat, open, writeFile } from "node:fs/promises";
import path from "node:path";
import {
  DeleteObjectCommand,
  GetObjectCommand,
  HeadObjectCommand,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";
import { safeEqual } from "./tokens";

/**
 * Storage abstraction. Media never touches Postgres: only object keys are stored.
 * - "local": files on disk, accessed through HMAC-signed URLs served by /api/storage (dev/self-host)
 * - "s3": any S3-compatible bucket (Cloudflare R2 etc.) with native presigned URLs
 */
export interface Storage {
  /** URL the browser PUTs the file to. */
  presignPut(key: string, mime: string, expiresInSec?: number): Promise<string>;
  /** Short-lived URL for reading a private object. */
  presignGet(key: string, expiresInSec?: number): Promise<string>;
  /** Size in bytes, or null if the object does not exist. */
  size(key: string): Promise<number | null>;
  /** First `n` bytes, used for magic-byte sniffing. */
  readHead(key: string, n: number): Promise<Uint8Array>;
  /** Whole object (used by the worker). */
  read(key: string): Promise<Buffer>;
  write(key: string, data: Buffer, mime: string): Promise<void>;
  remove(key: string): Promise<void>;
}

const SIGNING_SECRET = () => {
  const s = process.env.STORAGE_SIGNING_SECRET;
  if (!s || s.length < 32) throw new Error("STORAGE_SIGNING_SECRET must be set (>= 32 chars)");
  return s;
};

export function signLocal(method: "PUT" | "GET", key: string, exp: number): string {
  return createHmac("sha256", SIGNING_SECRET()).update(`${method}\n${key}\n${exp}`).digest("hex");
}

export function verifyLocal(method: "PUT" | "GET", key: string, exp: number, sig: string): boolean {
  if (!Number.isFinite(exp) || exp < Math.floor(Date.now() / 1000)) return false;
  return safeEqual(signLocal(method, key, exp), sig);
}

/** Keys are generated by us, but resolve defensively so a key can never escape the storage root. */
export function localPath(root: string, key: string): string {
  const resolved = path.resolve(root, key);
  if (!resolved.startsWith(path.resolve(root) + path.sep)) throw new Error("Invalid storage key");
  return resolved;
}

class LocalStorage implements Storage {
  private root = path.resolve(/*turbopackIgnore: true*/ process.env.LOCAL_STORAGE_DIR ?? "./.storage");
  private base = process.env.APP_URL ?? "http://localhost:3000";

  private url(method: "PUT" | "GET", key: string, expiresInSec: number) {
    const exp = Math.floor(Date.now() / 1000) + expiresInSec;
    const sig = signLocal(method, key, exp);
    return `${this.base}/api/storage/${key.split("/").map(encodeURIComponent).join("/")}?exp=${exp}&sig=${sig}`;
  }
  async presignPut(key: string, _mime: string, expiresInSec = 600) {
    return this.url("PUT", key, expiresInSec);
  }
  async presignGet(key: string, expiresInSec = 3600) {
    return this.url("GET", key, expiresInSec);
  }
  async size(key: string) {
    try {
      return (await stat(localPath(this.root, key))).size;
    } catch {
      return null;
    }
  }
  async readHead(key: string, n: number) {
    const fh = await open(localPath(this.root, key), "r");
    try {
      const buf = Buffer.alloc(n);
      const { bytesRead } = await fh.read(buf, 0, n, 0);
      return buf.subarray(0, bytesRead);
    } finally {
      await fh.close();
    }
  }
  async read(key: string) {
    return readFile(localPath(this.root, key));
  }
  async write(key: string, data: Buffer) {
    const p = localPath(this.root, key);
    await mkdir(path.dirname(p), { recursive: true });
    await writeFile(p, data);
  }
  async remove(key: string) {
    await rm(localPath(this.root, key), { force: true });
  }
}

class S3Storage implements Storage {
  private client = new S3Client({
    region: process.env.S3_REGION ?? "auto",
    endpoint: process.env.S3_ENDPOINT || undefined,
    credentials: {
      accessKeyId: process.env.S3_ACCESS_KEY_ID ?? "",
      secretAccessKey: process.env.S3_SECRET_ACCESS_KEY ?? "",
    },
  });
  private bucket = process.env.S3_BUCKET ?? "";

  async presignPut(key: string, mime: string, expiresInSec = 600) {
    return getSignedUrl(
      this.client,
      new PutObjectCommand({ Bucket: this.bucket, Key: key, ContentType: mime }),
      { expiresIn: expiresInSec },
    );
  }
  async presignGet(key: string, expiresInSec = 3600) {
    return getSignedUrl(this.client, new GetObjectCommand({ Bucket: this.bucket, Key: key }), {
      expiresIn: expiresInSec,
    });
  }
  async size(key: string) {
    try {
      const r = await this.client.send(new HeadObjectCommand({ Bucket: this.bucket, Key: key }));
      return r.ContentLength ?? null;
    } catch {
      return null;
    }
  }
  async readHead(key: string, n: number) {
    const r = await this.client.send(
      new GetObjectCommand({ Bucket: this.bucket, Key: key, Range: `bytes=0-${n - 1}` }),
    );
    return r.Body!.transformToByteArray();
  }
  async read(key: string) {
    const r = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    return Buffer.from(await r.Body!.transformToByteArray());
  }
  async write(key: string, data: Buffer, mime: string) {
    await this.client.send(
      new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: data, ContentType: mime }),
    );
  }
  async remove(key: string) {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

let instance: Storage | undefined;
export function getStorage(): Storage {
  if (!instance) instance = process.env.STORAGE_DRIVER === "s3" ? new S3Storage() : new LocalStorage();
  return instance;
}

export function storageRoot(): string {
  return path.resolve(/*turbopackIgnore: true*/ process.env.LOCAL_STORAGE_DIR ?? "./.storage");
}
